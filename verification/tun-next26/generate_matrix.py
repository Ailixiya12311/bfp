#!/usr/bin/env python3
"""Generate the frozen, reviewable next26 TUN/carrier matrix.

The output is declarative JSON and Mihomo YAML templates.  It deliberately
contains no credentials and no host-specific route commands.  The LA runner
must substitute the owned paths and client/server config files before launch.
"""

from __future__ import annotations

import argparse
import json
import pathlib
from typing import Any


ROOT = pathlib.Path(__file__).resolve().parent
ADDRESSES = {
    "numeric_ipv4": "192.0.2.10",
    "numeric_ipv6": "fd77:25::10",
    "fake_a": "198.18.0.10",
    "fake_aaaa": "fdfe:25::10",
}


def entry(name: str, carrier: str, family: str, target_kind: str, network: str, detour: bool = False) -> dict[str, Any]:
    target = ADDRESSES[target_kind]
    return {
        "id": name,
        "carrier": carrier,
        "carrier_family": family,
        "detour": detour,
        "business_network": network,
        "target_kind": target_kind,
        "target": target,
        "target_port": 18080,
        "expected_source": target,
        "probe": ["python3", "/opt/tun-next26/tun_harness.py", "probe", "--network", network, "--host", target, "--port", "18080", "--expect-source", target],
        "must_observe": {"tun_packets": True, "backend_packets": True, "carrier_packets": True, "carrier_reentry": False},
    }


def build_entries() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    # IPv4 carrier: direct paths exercise all four business destination forms.
    for carrier in ("udp", "tcp-fallback"):
        for target_kind in ("numeric_ipv4", "numeric_ipv6", "fake_a", "fake_aaaa"):
            for network in ("tcp", "udp"):
                rows.append(entry(f"direct_{carrier.replace('-', '_')}_v4_{target_kind}_{network}", carrier, "ipv4", target_kind, network))
    # IPv6 carrier: use the native numeric IPv6 backend and its two protocols.
    for carrier in ("udp", "tcp-fallback"):
        for network in ("tcp", "udp"):
            rows.append(entry(f"direct_{carrier.replace('-', '_')}_v6_numeric_ipv6_{network}", carrier, "ipv6", "numeric_ipv6", network))
    # Detoured carrier: the SOCKS5 detour rows focus on the fake-IP boundary.
    for carrier in ("udp", "tcp-fallback"):
        for target_kind in ("fake_a", "fake_aaaa"):
            for network in ("tcp", "udp"):
                rows.append(entry(f"detour_{carrier.replace('-', '_')}_v4_{target_kind}_{network}", carrier, "ipv4", target_kind, network, True))
    for carrier in ("udp", "tcp-fallback"):
        for network in ("tcp", "udp"):
            rows.append(entry(f"detour_{carrier.replace('-', '_')}_v6_numeric_ipv6_{network}", carrier, "ipv6", "numeric_ipv6", network, True))
    assert len(rows) == 32, len(rows)
    return rows


def negative_entries() -> list[dict[str, Any]]:
    return [
        {"id": "unknown_fake_a", "kind": "unknown_fake_mapping", "network": "tcp", "target": "198.18.0.250", "target_port": 18080, "expected": "fail_before_bfp_open"},
        {"id": "unknown_fake_aaaa", "kind": "unknown_fake_mapping", "network": "udp", "target": "fdfe:25::fa", "target_port": 18080, "expected": "fail_before_bfp_open"},
        {"id": "bfp_server_stopped", "kind": "dependency_down", "expected": "probe_timeout_or_refused_and_backend_count_unchanged"},
        {"id": "tun_route_removed", "kind": "fail_closed_route", "expected": "probe_fails_and_local_echo_count_unchanged"},
        {"id": "socks_detour_stopped", "kind": "dependency_down", "expected": "detoured_probe_fails"},
        {"id": "wrong_pinned_key", "kind": "credential_negative", "expected": "session_authentication_fails"},
        {"id": "detour_missing", "kind": "dialer_proxy_reference", "expected": "config_rejected_after_bfp_proxyinfo_wiring"},
        {"id": "detour_self", "kind": "dialer_proxy_cycle", "expected": "config_rejected_after_bfp_proxyinfo_wiring"},
        {"id": "detour_cycle", "kind": "dialer_proxy_cycle", "expected": "config_rejected_after_bfp_proxyinfo_wiring"},
    ]


def mihomo_yaml(path_name: str, proxy_name: str, ip_version: str, detour: bool) -> str:
    detour_block = """
  - name: DETOUR_SOCKS
    type: socks5
    server: 192.0.2.30
    port: 19090
    udp: true
""" if detour else ""
    dialer = "    dialer-proxy: DETOUR_SOCKS\n" if detour else ""
    return f"""# Generated by verification/tun-next26/generate_matrix.py
# Fill BFP_CLIENT_CONFIG with an owned, authenticated client.json before use.
mixed-port: 19000
mode: rule
log-level: debug
ipv6: true
dns:
  enable: true
  listen: 0.0.0.0:1053
  enhanced-mode: fake-ip
  fake-ip-range: 198.18.0.1/16
  fake-ip-range6: fdfe:25::/64
  nameserver:
    - 127.0.0.1:15353
  proxy-server-nameserver:
    - 127.0.0.1:15353
tun:
  enable: true
  device: mihomo-tun
  stack: gvisor
  auto-route: false
  auto-detect-interface: false
  auto-redirect: false
  strict-route: true
  dns-hijack:
    - any:53
  inet6-address:
    - fd7e:25::1/126
proxies:
  - name: {proxy_name}
    type: bfp
    client-config-file: BFP_CLIENT_CONFIG
    udp: true
    ip-version: {ip_version}
{dialer}{detour_block}rules:
  - MATCH,{proxy_name}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default=str(ROOT))
    args = ap.parse_args()
    out = pathlib.Path(args.output).resolve()
    out.mkdir(parents=True, exist_ok=True)
    entries = build_entries()
    document = {
        "schema": "tun-next26-matrix-v1",
        "scope": "owned Linux network namespace; no host network; no ICMP",
        "addresses": ADDRESSES,
        "carrier_endpoints": {"ipv4": "bfp-carrier-v4.test:51880", "ipv6": "[bfp-carrier-v6.test]:51880"},
        "entries": entries,
        "negative_entries": negative_entries(),
        "acceptance_rule": "A row passes only when route-get, TUN pcap, BFP/session evidence, backend pcap, and no carrier reentry are all present.",
        "unimplemented_boundary": "detour_missing/self/cycle are not countable as passed until BFP ProxyInfo exposes DialerProxy to Mihomo config validation.",
    }
    (out / "matrix.json").write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    configs = out / "configs"
    configs.mkdir(exist_ok=True)
    for carrier_family, ip_version, detour in (("ipv4", "ipv4", False), ("ipv4", "ipv4", True), ("ipv6", "ipv6", False), ("ipv6", "ipv6", True)):
        name = f"mihomo-{'detour-' if detour else ''}{carrier_family}.yaml"
        (configs / name).write_text(mihomo_yaml(name, "BFP_DETOUR" if detour else "BFP_DIRECT", ip_version, detour), encoding="utf-8")
    (out / "negative-matrix.json").write_text(json.dumps(negative_entries(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({"output": str(out), "entries": len(entries), "negative_entries": len(negative_entries()), "configs": 4}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
